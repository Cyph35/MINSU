// Builds src/components/map/layers.ts — three map layers (story regions, provinces, administrative regions)
// from current PSGC boundaries (github.com/faeldon/philippines-json-maps, "latest", medres).
// Usage: node scripts/build-map2.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const slug = (s) => s.toLowerCase().replace(/\(.*?\)/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const ADMIN = { 9: 'region-ix', 10: 'region-x', 11: 'region-xi', 12: 'region-xii', 16: 'caraga', 19: 'barmm', 17: 'mimaropa' };
const STORY = {
  'lanao-del-sur': 'lanao',
  'maguindanao-del-norte': 'maguindanao-cotabato', 'maguindanao-del-sur': 'maguindanao-cotabato',
  'special-geographic-area': 'maguindanao-cotabato', cotabato: 'maguindanao-cotabato',
  'zamboanga-del-norte': 'zamboanga', 'zamboanga-del-sur': 'zamboanga', 'zamboanga-sibugay': 'zamboanga',
  basilan: 'basilan', 'city-of-isabela': 'basilan', sulu: 'sulu', 'tawi-tawi': 'tawi-tawi',
  'davao-del-norte': 'davao', 'davao-del-sur': 'davao', 'davao-oriental': 'davao', 'davao-de-oro': 'davao', 'davao-occidental': 'davao',
  bukidnon: 'northern-mindanao', camiguin: 'northern-mindanao', 'lanao-del-norte': 'northern-mindanao', 'misamis-occidental': 'northern-mindanao', 'misamis-oriental': 'northern-mindanao',
  'south-cotabato': 'soccsksargen', 'sultan-kudarat': 'soccsksargen', sarangani: 'soccsksargen',
  'agusan-del-norte': 'caraga', 'agusan-del-sur': 'caraga', 'surigao-del-norte': 'caraga', 'surigao-del-sur': 'caraga', 'dinagat-islands': 'caraga',
  palawan: 'palawan',
};
const features = [];
for (const f of readdirSync('scripts/geo')) {
  for (const ft of JSON.parse(readFileSync(join('scripts/geo', f), 'utf8')).features) {
    const id = slug(ft.properties.adm2_en);
    if (!STORY[id]) continue; // drops Mindoro, Marinduque, Romblon
    const reg = Math.round(ft.properties.adm1_psgc / 1e8);
    // Sulu is drawn in BARMM to match the course slides; the 2024 SC ruling is explained in a tooltip.
    const admin = id === 'sulu' ? 'barmm' : ADMIN[reg];
    features.push({ ...ft, properties: { province: id, name: ft.properties.adm2_en, admin, story: STORY[id] } });
  }
}
const dir = mkdtempSync(join(tmpdir(), 'map2-'));
writeFileSync(join(dir, 'in.json'), JSON.stringify({ type: 'FeatureCollection', features }));
const run = (extra, key, out) => {
  execFileSync('npx', ['-y', 'mapshaper@0.6', join(dir, 'in.json'), '-clean', ...extra, '-simplify', '6%', 'keep-shapes',
    '-filter-islands', 'min-area=6km2', '-proj', '+proj=merc', '-o', 'format=svg', 'width=1000', 'margin=10', `svg-data=${key}`, join(dir, out)], { stdio: 'inherit' });
  const svg = readFileSync(join(dir, out), 'utf8');
  const paths = {};
  for (const m of svg.matchAll(new RegExp(`<path d="([^"]+)"[^>]*data-${key}="([^"]+)"`, 'g'))) paths[m[2]] = (paths[m[2]] ? paths[m[2]] + ' ' : '') + m[1];
  return { vb: svg.match(/viewBox="([^"]+)"/)[1], paths };
};
const provinces = run([], 'province', 'p.svg');
const admin = run(['-dissolve', 'admin'], 'admin', 'a.svg');
const story = run(['-dissolve', 'story'], 'story', 's.svg');
const meta = Object.fromEntries(features.map((f) => [f.properties.province, { name: f.properties.name, admin: f.properties.admin, story: f.properties.story }]));
writeFileSync('src/components/map/layers.ts', `// AUTO-GENERATED by scripts/build-map2.mjs — do not edit by hand.
// Boundaries: PSGC-based GeoJSON from github.com/faeldon/philippines-json-maps (latest), simplified.
export const MAP_VIEWBOX = ${JSON.stringify(provinces.vb)};
export const STORY_PATHS: Record<string, string> = ${JSON.stringify(story.paths)};
export const ADMIN_PATHS: Record<string, string> = ${JSON.stringify(admin.paths)};
export const PROVINCE_PATHS: Record<string, string> = ${JSON.stringify(provinces.paths)};
export const PROVINCE_META: Record<string, { name: string; admin: string; story: string }> = ${JSON.stringify(meta, null, 1)};
`);
console.log('viewBoxes', provinces.vb, admin.vb, story.vb);
console.log('story', Object.keys(story.paths).length, 'admin', Object.keys(admin.paths), 'prov', Object.keys(provinces.paths).length);
