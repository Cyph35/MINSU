// Fetches openly licensed images from Wikimedia Commons with author + license metadata.
// Usage: node scripts/fetch-media.mjs   → writes public/media/<slug>/*.jpg and src/data/media.generated.ts
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';

const UA = 'SugilanonSaKalinaw/1.0 (educational student project)';
const Q = {
  lanao: ['Lake Lanao', 'Torogan Maranao house', 'Okir Maranao design', 'Sarimanok'],
  'maguindanao-cotabato': ['Rio Grande de Mindanao', 'Cotabato City mosque', 'Kutiyapi', 'Kulintang Maguindanao'],
  zamboanga: ['Fort Pilar Zamboanga', 'Vinta boat Zamboanga', 'Zamboanga City Hall', 'Subanen'],
  basilan: ['Basilan island', 'Yakan weaving', 'Yakan cloth', 'Isabela City Basilan'],
  sulu: ['Jolo island Sulu', 'Moro kris sword', 'Sulu archipelago', 'Tausug language map'],
  'tawi-tawi': ['Bongao Peak', 'Sheik Karimul Makhdum Mosque', 'Badjao stilt houses', 'Bongao Tawi-Tawi'],
  davao: ['Mount Apo', 'Bagobo', 'Davao Gulf', 'Mandaya'],
  'northern-mindanao': ['Bukidnon landscape', 'Kaamulan', 'Cagayan de Oro skyline', 'Lanao del Norte Maria Cristina Falls'],
  soccsksargen: ['Lake Sebu', 'Tnalak', 'Sarangani Bay', 'Tboli'],
  palawan: ['Tabon Cave', 'Manunggul Jar', 'Puerto Princesa Subterranean River', 'Coron Island'],
};
const OK = /^(public domain|pd|cc0|cc by(-sa)? ?[\d.]*)/i;
const strip = (h = '') => h.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
const used = new Set();
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function api(u) {
  for (let t = 0; t < 6; t++) {
    await sleep(2500);
    const txt = await fetch(u, { headers: { 'User-Agent': UA } }).then((r) => r.text());
    if (txt.startsWith('{')) return JSON.parse(txt);
    await sleep(10000 * (t + 1));
  }
  throw new Error('rate limited');
}
const STORE = 'scripts/media.json';
const out = existsSync(STORE) ? JSON.parse(readFileSync(STORE, 'utf8')) : {};
Object.values(out).flat().forEach((m) => used.add('File:' + m.file));
const only = process.argv.slice(2);
for (const [slug, qs] of Object.entries(Q)) {
  if (only.length ? !only.includes(slug) : out[slug]?.length) continue;
  mkdirSync(`public/media/${slug}`, { recursive: true });
  out[slug] = [];
  for (const [i, q] of qs.entries()) {
    const u = new URL('https://commons.wikimedia.org/w/api.php');
    Object.entries({ action: 'query', format: 'json', generator: 'search', gsrsearch: `${q} filetype:bitmap`, gsrnamespace: '6', gsrlimit: '12', prop: 'imageinfo', iiprop: 'url|extmetadata|mime', iiurlwidth: '1600' }).forEach(([k, v]) => u.searchParams.set(k, v));
    const res = await api(u);
    const pages = Object.values(res.query?.pages ?? {}).sort((a, b) => a.index - b.index);
    const pick = pages.find((p) => {
      const ii = p.imageinfo?.[0]; const m = ii?.extmetadata ?? {};
      const lic = m.LicenseShortName?.value ?? '';
      return ii && /jpeg|png/.test(ii.mime) && OK.test(lic) && !/NC|ND/.test(lic) && !used.has(p.title) && (ii.thumbwidth ?? 0) >= 800;
    });
    if (!pick) { console.log('NO MATCH', slug, q); continue; }
    used.add(pick.title);
    const ii = pick.imageinfo[0]; const m = ii.extmetadata;
    const file = `public/media/${slug}/${i}.jpg`;
    const buf = Buffer.from(await fetch(ii.thumburl, { headers: { 'User-Agent': UA } }).then((r) => r.arrayBuffer()));
    writeFileSync(file, buf);
    out[slug].push({
      kind: 'image', src: `/media/${slug}/${i}.jpg`, width: ii.thumbwidth, height: ii.thumbheight,
      file: pick.title.replace(/^File:/, ''),
      title: pick.title.replace(/^File:/, '').replace(/\.\w+$/, ''),
      description: strip(m.ImageDescription?.value).slice(0, 220),
      credit: strip(m.Artist?.value) || 'Unknown author', license: strip(m.LicenseShortName?.value),
      sourceUrl: ii.descriptionurl, query: q,
    });
    writeFileSync(STORE, JSON.stringify(out, null, 2));
    console.log(slug, q, '→', pick.title, '|', strip(m.LicenseShortName?.value));
  }
}
writeFileSync('src/data/media.generated.ts', `// AUTO-GENERATED by scripts/fetch-media.mjs — Wikimedia Commons metadata.\nexport interface CommonsImage { kind: 'image'; src: string; width: number; height: number; title: string; description: string; credit: string; license: string; sourceUrl: string; query: string }\nexport const commons: Record<string, CommonsImage[]> = ${JSON.stringify(out, null, 2)};\n`);
