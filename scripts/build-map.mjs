// One-off: builds src/components/map/paths.ts from GADM-derived province GeoJSON.
// Usage: node scripts/build-map.mjs /path/to/Provinces.json
// Source: github.com/macoymejia/geojsonph (GADM boundaries, academic/non-commercial use).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const GROUPS = {
  lanao: ['Lanao del Sur'],
  'maguindanao-cotabato': ['Maguindanao', 'Shariff Kabunsuan', 'North Cotabato'],
  zamboanga: ['Zamboanga del Norte', 'Zamboanga del Sur', 'Zamboanga Sibugay'],
  basilan: ['Basilan'],
  sulu: ['Sulu'],
  'tawi-tawi': ['Tawi-Tawi'],
  davao: ['Compostela Valley', 'Davao Oriental', 'Davao del Norte', 'Davao del Sur'],
  'northern-mindanao': ['Bukidnon', 'Lanao del Norte', 'Misamis Oriental', 'Misamis Occidental', 'Camiguin'],
  soccsksargen: ['South Cotabato', 'Sultan Kudarat', 'Sarangani'],
  palawan: ['Palawan'],
  caraga: ['Agusan del Norte', 'Agusan del Sur', 'Surigao del Norte', 'Surigao del Sur', 'Dinagat Islands'],
};
const lookup = Object.fromEntries(Object.entries(GROUPS).flatMap(([g, ns]) => ns.map((n) => [n, g])));
const src = JSON.parse(readFileSync(process.argv[2], 'utf8'));
src.features = src.features
  .filter((f) => lookup[f.properties.NAME_1])
  .map((f) => ({ ...f, properties: { group: lookup[f.properties.NAME_1] } }));
const dir = mkdtempSync(join(tmpdir(), 'map-'));
writeFileSync(join(dir, 'in.json'), JSON.stringify(src));
execFileSync('npx', ['-y', 'mapshaper@0.6', join(dir, 'in.json'),
  '-dissolve', 'group', '-simplify', '1.2%', 'keep-shapes', '-filter-islands', 'min-area=8km2',
  '-proj', '+proj=merc', '-o', 'format=svg', 'width=1000', 'margin=10', 'svg-data=group', join(dir, 'out.svg')], { stdio: 'inherit' });
const svg = readFileSync(join(dir, 'out.svg'), 'utf8');
const vb = svg.match(/viewBox="([^"]+)"/)[1];
const paths = {};
for (const m of svg.matchAll(/<path d="([^"]+)"[^>]*data-group="([^"]+)"/g)) paths[m[2]] = m[1];
const out = `// AUTO-GENERATED by scripts/build-map.mjs — do not edit by hand.
// Boundaries simplified from GADM via github.com/macoymejia/geojsonph (educational use).
export const MAP_VIEWBOX = ${JSON.stringify(vb)};
export const MAP_PATHS: Record<string, string> = ${JSON.stringify(paths, null, 2)};
`;
writeFileSync('src/components/map/paths.ts', out);
console.log(vb, Object.keys(paths), out.length, 'bytes');
